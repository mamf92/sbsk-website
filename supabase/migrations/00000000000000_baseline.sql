-- Baseline: the objects that were created in the Supabase dashboard before this repo kept
-- migrations (security plan S4.1, docs/plans/SECURITY_AND_RELIABILITY.md; phase 2 step 0,
-- docs/plans/phase-2-admin-page.md).
--
-- Captured from production (project ifdxcpntwugfggcripkw) on 2026-11-18 with pg_catalog reads
-- through the Supabase MCP. It describes the live state as it was then, so a fresh database
-- (local `supabase start`, CI, the staging project in #262) can be built from migrations alone.
--
-- Production already has all of this. **Do not apply it there**: mark it applied instead with
--   supabase migration repair --status applied 00000000000000
--
-- Everything is idempotent (`if not exists`, `create or replace`, `drop … if exists`), and the
-- later migrations that were written against the live database (20260809200650 onward) re-run
-- cleanly on top of it.

-- The register of club members, maintained by the board. `is_admin` is the only admin authority.
create table if not exists public.members (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  surname text not null,
  phone text not null,
  address text not null,
  postcode text not null,
  city text not null,
  email text not null constraint members_email_key unique,
  is_admin boolean not null default false,
  supabase_id uuid,
  created_at timestamptz default now()
);

-- A member's own presentation. Created by handle_new_user() when an auth user is created.
create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  supabase_id uuid not null references auth.users (id) on update cascade on delete cascade,
  name text,
  surname text,
  email varchar not null,
  address text,
  postcode text,
  city text,
  bio text,
  photo_url text,
  is_admin boolean not null default false
);

alter table public.members enable row level security;
alter table public.profiles enable row level security;

-- Live grants (Supabase's old default privileges). RLS is what limits them; 20261118180100
-- narrows them.
grant all on public.members, public.profiles to anon, authenticated, service_role;

create or replace function public.member_is_admin()
returns boolean
language sql
security definer
set search_path to 'public'
as $$
  select exists (
    select 1 from public.members
    where supabase_id = auth.uid()
      and is_admin = true
  );
$$;

-- Before-insert on auth.users: only emails on the register may create an account (invite-only).
create or replace function public.hook_restrict_signup_by_email_list()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  if new.email is null or new.email = '' then
    raise exception 'Signup rejected: Email is required';
  end if;

  if not exists (
    select 1 from public.members
    where lower(email) = lower(new.email)
  ) then
    raise exception 'Signup rejected: Email % is not yet a registered member email.', new.email;
  end if;

  return new;
end;
$$;

-- After-insert on auth.users: create the profile and link the register row.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  insert into public.profiles (supabase_id, email)
  values (new.id, lower(new.email));

  update public.members
  set supabase_id = new.id
  where lower(email) = lower(new.email);

  return new;
end;
$$;

-- After-update on auth.users: keep the profile's copy of the email current.
create or replace function public.sync_profile_email_on_auth_update()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  update public.profiles
  set email = new.email
  where supabase_id = new.id;
  return new;
end;
$$;

create or replace function public.prevent_admin_escalation()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  if tg_op = 'INSERT' then
    if new.is_admin is true and not public.member_is_admin() then
      raise exception 'Not allowed to set admin status';
    end if;
  elsif tg_op = 'UPDATE' then
    if new.is_admin is distinct from old.is_admin and not public.member_is_admin() then
      raise exception 'Not allowed to change admin status';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_before on auth.users;
create trigger on_auth_user_created_before
  before insert on auth.users
  for each row execute function public.hook_restrict_signup_by_email_list();

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

drop trigger if exists on_auth_user_updated on auth.users;
create trigger on_auth_user_updated
  after update on auth.users
  for each row execute function public.sync_profile_email_on_auth_update();

drop trigger if exists prevent_admin_escalation_trigger on public.profiles;
create trigger prevent_admin_escalation_trigger
  before insert or update on public.profiles
  for each row execute function public.prevent_admin_escalation();

-- Supabase's "enable RLS on new tables" event trigger, as the dashboard installed it.
create or replace function public.rls_auto_enable()
returns event_trigger
language plpgsql
security definer
set search_path to 'pg_catalog'
as $$
declare
  cmd record;
begin
  for cmd in
    select *
    from pg_event_trigger_ddl_commands()
    where command_tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      and object_type in ('table', 'partitioned table')
  loop
    if cmd.schema_name is not null and cmd.schema_name in ('public') then
      begin
        execute format('alter table if exists %s enable row level security', cmd.object_identity);
        raise log 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      exception
        when others then
          raise log 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      end;
    else
      raise log 'rls_auto_enable: skip % (not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
    end if;
  end loop;
end;
$$;

-- Event triggers need superuser; a role without it (some hosted setups) skips this, and every
-- migration in this repo enables RLS explicitly anyway.
do $$
begin
  if not exists (select 1 from pg_event_trigger where evtname = 'ensure_rls') then
    create event trigger ensure_rls on ddl_command_end
      when tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      execute function public.rls_auto_enable();
  end if;
exception
  when insufficient_privilege then
    raise notice 'Skipping event trigger ensure_rls: insufficient privilege';
end;
$$;

-- The register's policies as created in the dashboard (20261118180100 replaces them).
drop policy if exists "Admins can view members" on public.members;
create policy "Admins can view members"
  on public.members for select to authenticated
  using (public.member_is_admin());

drop policy if exists "Admins can create members" on public.members;
create policy "Admins can create members"
  on public.members for insert to authenticated
  with check (public.member_is_admin());

drop policy if exists "Admins can update members" on public.members;
create policy "Admins can update members"
  on public.members for update to authenticated
  using (public.member_is_admin())
  with check (public.member_is_admin());

drop policy if exists "Admins can delete members" on public.members;
create policy "Admins can delete members"
  on public.members for delete to authenticated
  using (public.member_is_admin());

